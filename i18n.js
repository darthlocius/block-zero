let currentLanguage = normalizeLanguage(safeStorageGet(LANGUAGE_STORAGE_KEY));
const languageListeners = new Set();

function normalizeLanguage(lang) {
  return Object.hasOwn(LANGUAGES, lang) ? lang : DEFAULT_LANGUAGE;
}

function interpolate(text, params = {}) {
  return String(text).replace(/\{(\w+)\}/g, (match, key) => (
    Object.hasOwn(params, key) ? String(params[key]) : match
  ));
}

function getLanguage() {
  return currentLanguage;
}

function t(key, params = {}) {
  const selected = I18N[currentLanguage] || I18N[DEFAULT_LANGUAGE];
  const fallback = I18N[DEFAULT_LANGUAGE] || {};
  const value = selected[key] ?? fallback[key] ?? key;
  return interpolate(value, params);
}

function setLanguage(lang) {
  const next = normalizeLanguage(lang);
  if (next === currentLanguage) {
    updateStaticTranslations();
    updateLanguageSwitcher();
    return currentLanguage;
  }
  currentLanguage = next;
  safeStorageSet(LANGUAGE_STORAGE_KEY, currentLanguage);
  updateStaticTranslations();
  updateLanguageSwitcher();
  for (const listener of languageListeners) listener(currentLanguage);
  return currentLanguage;
}

function addLanguageChangeListener(listener) {
  if (typeof listener !== "function") return () => {};
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

function updateLanguageSwitcher(root = document) {
  root.querySelectorAll("[data-language-option]").forEach((button) => {
    const active = button.dataset.languageOption === currentLanguage;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function updateStaticTranslations(root = document) {
  document.documentElement.lang = t("html.lang");
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", t(element.dataset.i18nTitle));
  });
  updateLanguageSwitcher(root);
}

